// 方案 B「雾霾蓝紫」：中性灰底 + 低饱和蓝紫强调。背景不带色偏，强调色只做点缀，
// 高对比/中对比变体由基色按比例推导。

private fun Color.darker(f: Float): Color = Color(
    red * (1 - f),
    green * (1 - f),
    blue * (1 - f),
    alpha,
)

private fun Color.lighter(f: Float): Color = Color(
    red + (1 - red) * f,
    green + (1 - green) * f,
    blue + (1 - blue) * f,
    alpha,
)

